"""Scheduled UDP burst sender on ext-DN (DL leg of co-tenant / multi-rogue attacks).

Deployment
----------
Runs on ``oai-ext-dn`` (or is invoked from rogue via shell wrappers). Rogue UL
traffic is generated by ``co_tenant_load.py`` on the PDU path; this module handles
the complementary DL burst toward rogue PDU IPs.

Modes (``--mode``)
------------------
* ``dl_burst_sender`` — legacy single-target dual-pulse DL leg
* ``multi-rogue-dl`` — continuous scheduled bursts to N rogue PDUs
* ``multi-rogue-dl-sync`` — setpoint-synced DL peaks (CNI trigger or open-loop)

Stdout ends with ``[EXT-DN-SYNC] done: bursts=…`` — parsed by ``orchestrate.py``
integrity gates for sync-style attacks.
"""
from __future__ import annotations

import argparse
import json
import socket
import sys
import time


UDP_DATAGRAM_MAX = 1200  # GTP/oaitun MTU-safe datagram size
BURST_SLICE_S = 0.005
SNDBUF_BYTES = 4 * 1024 * 1024


def _send_burst_bytes(sock, target, port, nbytes, fill_byte=b"\xdc"):
    sent = 0
    while sent < nbytes:
        chunk_len = min(UDP_DATAGRAM_MAX, nbytes - sent)
        try:
            sock.sendto(fill_byte * chunk_len, (target, port))
            sent += chunk_len
        except OSError:
            break
    return sent


def _burst_pps(sock, targets, port, payload: bytes, pps: int, burst_ms: float) -> int:
    """Sustained multi-target contention for *burst_ms* at ~pps datagrams/s total."""
    slice_s = BURST_SLICE_S
    per_slice = max(1, int(pps * slice_s))
    end = time.monotonic() + burst_ms / 1000.0
    sent = 0
    i = 0
    n_dests = len(targets)
    while time.monotonic() < end:
        t_slice_end = time.monotonic() + slice_s
        for _ in range(per_slice):
            try:
                sock.sendto(payload, (targets[i % n_dests], port))
                sent += 1
                i += 1
            except OSError:
                pass
        rem = t_slice_end - time.monotonic()
        if rem > 0:
            time.sleep(rem)
    return sent


def run_sender(args: argparse.Namespace) -> int:
    sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    period_s = args.period_ms / 1000.0
    phase_s = args.phase_ms / 1000.0
    dl_window_s = max(0.001, period_s - phase_s)
    targets = list(dict.fromkeys(args.target))
    if not targets:
        raise SystemExit("at least one --target is required")
    if args.mbps_per_target is not None:
        rate_per_target_mbps = float(args.mbps_per_target)
    else:
        rate_per_target_mbps = float(args.total_mbps) / 2.0
    target_rate_bps = rate_per_target_mbps * 1e6
    bytes_per_burst = max(args.burst_bytes, int((target_rate_bps / 8.0) * period_s))

    t_start = time.monotonic()
    t_end = t_start + args.duration
    bursts = 0
    sent = 0
    sent_per_target = {target: 0 for target in targets}
    while time.monotonic() < t_end:
        t_cycle = time.monotonic()
        if phase_s > 0:
            time.sleep(min(phase_s, max(0.0, t_end - time.monotonic())))
        if time.monotonic() >= t_end:
            break
        for target in targets:
            burst_sent = _send_burst_bytes(sock, target, args.port, bytes_per_burst)
            sent += burst_sent
            sent_per_target[target] += burst_sent
        bursts += 1
        rem = period_s - (time.monotonic() - t_cycle)
        if rem > 0:
            time.sleep(rem)

    duration_actual = time.monotonic() - t_start
    achieved = (sent * 8.0) / duration_actual / 1e6 if duration_actual > 0 else 0.0
    summary = {
        "mode": args.mode,
        "run_id": args.run_id or None,
        "target": targets[0] if len(targets) == 1 else None,
        "targets": targets,
        "target_count": len(targets),
        "port": args.port,
        "period_ms": args.period_ms,
        "phase_ms": args.phase_ms,
        "total_mbps_requested": args.total_mbps,
        "requested_mbps_per_target": rate_per_target_mbps,
        "requested_aggregate_mbps": rate_per_target_mbps * len(targets),
        "achieved_dl_mbps_sender": round(achieved, 3),
        "achieved_sender_mbps": round(achieved, 3),
        "bytes_sent": sent,
        "bytes_sent_per_target": sent_per_target,
        "bursts_completed": bursts,
        "duration_actual_s": round(duration_actual, 3),
        "dl_window_s": round(dl_window_s, 4),
    }
    print(json.dumps(summary))
    if args.out_summary:
        with open(args.out_summary, "w", encoding="utf-8") as f:
            json.dump(summary, f, indent=2)
            f.write("\n")
    return 0


def run_sync_sender(args: argparse.Namespace) -> int:
    """Peak DL bursts aligned to setpoint rhythm (open-loop or CNI trigger)."""
    targets = list(dict.fromkeys(args.target))
    if not targets:
        raise SystemExit("at least one --target is required")
    if args.burst_ms <= 0 or args.pps <= 0 or args.size <= 0:
        raise SystemExit("sync peak parameters must be > 0")
    payload = b"\xdc" * max(1, min(UDP_DATAGRAM_MAX, int(args.size)))
    sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    sock.setsockopt(socket.SOL_SOCKET, socket.SO_SNDBUF, SNDBUF_BYTES)

    bursts = 0
    packets = 0
    t_end = time.monotonic() + args.duration
    open_loop = bool(args.open_loop)

    try:
        if open_loop:
            if args.rate_hz <= 0:
                print("[EXT-DN-SYNC] ERROR: --rate-hz must be > 0", flush=True)
                return 2
            period_s = 1.0 / args.rate_hz
            print(
                "[EXT-DN-SYNC] mode=open-loop rate=%.3fHz phase=%.1fms "
                "burst=%.0fms pps=%d size=%dB targets=%d port=%d dur=%.0fs"
                % (args.rate_hz, args.phase_ms, args.burst_ms, args.pps, args.size,
                   len(targets), args.port, args.duration),
                flush=True,
            )
            next_burst = time.monotonic() + max(0.0, args.phase_ms / 1000.0)
            while time.monotonic() < t_end:
                now = time.monotonic()
                if now < next_burst:
                    time.sleep(min(0.01, next_burst - now))
                    continue
                t0 = time.monotonic_ns()
                n = _burst_pps(sock, targets, args.port, payload, args.pps, args.burst_ms)
                packets += n
                bursts += 1
                dt_ms = (time.monotonic_ns() - t0) / 1e6
                if bursts <= 3 or bursts % 20 == 0:
                    print(
                        "[EXT-DN-SYNC] burst #%d: %d pkts in %.1fms (open-loop)"
                        % (bursts, n, dt_ms),
                        flush=True,
                    )
                next_burst += period_s
                if next_burst < time.monotonic() - period_s:
                    next_burst = time.monotonic() + period_s
        else:
            listener = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
            listener.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
            listener.bind(("0.0.0.0", args.listen_port))
            print(
                "[EXT-DN-SYNC] mode=trigger-oracle listen=:%d burst=%.0fms pps=%d "
                "size=%dB targets=%d port=%d dur=%.0fs"
                % (args.listen_port, args.burst_ms, args.pps, args.size,
                   len(targets), args.port, args.duration),
                flush=True,
            )
            while True:
                remaining = t_end - time.monotonic()
                if remaining <= 0:
                    break
                listener.settimeout(min(remaining, 1.0))
                try:
                    listener.recvfrom(256)
                except socket.timeout:
                    continue
                except OSError:
                    continue
                listener.setblocking(False)
                while True:
                    try:
                        listener.recvfrom(256)
                    except (BlockingIOError, OSError):
                        break
                listener.setblocking(True)
                t0 = time.monotonic_ns()
                n = _burst_pps(sock, targets, args.port, payload, args.pps, args.burst_ms)
                packets += n
                bursts += 1
                dt_ms = (time.monotonic_ns() - t0) / 1e6
                if bursts <= 3 or bursts % 20 == 0:
                    print(
                        "[EXT-DN-SYNC] burst #%d: %d pkts in %.1fms"
                        % (bursts, n, dt_ms),
                        flush=True,
                    )
    finally:
        sock.close()

    duration_actual = max(0.001, args.duration)
    peak_mbps = (args.pps * len(payload) * 8) / 1e6
    summary = {
        "mode": args.mode,
        "run_id": args.run_id or None,
        "targets": targets,
        "target_count": len(targets),
        "port": args.port,
        "open_loop": open_loop,
        "rate_hz": args.rate_hz if open_loop else None,
        "phase_ms": args.phase_ms if open_loop else 0.0,
        "burst_ms": args.burst_ms,
        "pps": args.pps,
        "payload_bytes": len(payload),
        "peak_aggregate_mbps": round(peak_mbps, 3),
        "bursts_completed": bursts,
        "packets_sent": packets,
        "bytes_sent": packets * len(payload),
        "achieved_sender_mbps": round(
            (packets * len(payload) * 8.0) / duration_actual / 1e6, 3
        ),
        "duration_actual_s": round(duration_actual, 3),
        "threat_model": "pure_dl_prb_contention_sync",
    }
    print(
        "[EXT-DN-SYNC] done: bursts=%d pkts=%d bytes≈%d"
        % (bursts, packets, packets * len(payload)),
        flush=True,
    )
    print(json.dumps(summary))
    if args.out_summary:
        with open(args.out_summary, "w", encoding="utf-8") as f:
            json.dump(summary, f, indent=2)
            f.write("\n")
    return 0 if bursts > 0 else 1


def main() -> int:
    ap = argparse.ArgumentParser(description="FlyBlind ext-DN DL burst sender")
    ap.add_argument("--target", action="append", required=True, help="ROGUE PDU IP (repeatable)")
    ap.add_argument("--port", type=int, default=5203)
    ap.add_argument("--duration", type=float, required=True)
    ap.add_argument("--period-ms", type=int, default=40)
    ap.add_argument("--phase-ms", type=float, default=0)
    ap.add_argument("--burst-bytes", type=int, default=50000)
    ap.add_argument("--total-mbps", type=float, default=20.0)
    ap.add_argument("--mbps-per-target", type=float, default=None)
    ap.add_argument(
        "--mode",
        choices=["dl_burst_sender", "multi-rogue-dl", "multi-rogue-dl-sync"],
        default="dl_burst_sender",
    )
    ap.add_argument("--open-loop", action="store_true")
    ap.add_argument("--rate-hz", type=float, default=10.0)
    ap.add_argument("--listen-port", type=int, default=47555)
    ap.add_argument("--burst-ms", type=float, default=25.0)
    ap.add_argument("--pps", type=int, default=20000)
    ap.add_argument("--size", type=int, default=1400)
    ap.add_argument("--run-id", default="")
    ap.add_argument("--out-summary", default="")
    args = ap.parse_args()
    if args.mode == "multi-rogue-dl-sync":
        return run_sync_sender(args)
    return run_sender(args)


if __name__ == "__main__":
    sys.exit(main())
